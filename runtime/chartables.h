/* The game's tables indexed by character number, moved to the extension RAM
 * with room for the PSP characters (tools/psp/chartables.py has the list and
 * the why). The recompiler rewrote the literals; this copies the tables. */
#pragma once
#include <stdint.h>

typedef struct {
    uint32_t dc;       /* the table on the Dreamcast */
    uint32_t count;    /* entries copied from there */
    uint32_t size;     /* bytes per entry */
    uint32_t ext;      /* where it is now (extension RAM) */
    uint32_t entries;  /* room for this many (0x2A for a character table: 0x00-0x29) */
} CharTable;

/* generated by the recompiler (char_tables.c) */
extern const CharTable g_char_tables[];
extern const unsigned g_char_table_count;

/* constants of the game's code read from the memory (chartables.py, IMMEDIATES):
 * the instructions' own values, written at g_imm_base at boot (the add-on's
 * patches change some) */
extern const uint32_t g_imm_base;
extern const uint32_t g_imm_defaults[];
extern const unsigned g_imm_count;

/* the PSP characters' entries (psp_tables.c from tools/psp/build_char.py, or
 * psp_none.c): records of u32 address, u32 length, the bytes, padded to 4 */
extern const uint8_t g_psp_char_data[];
extern const unsigned g_psp_char_data_size;

/* at boot and reset, once 1ST_READ.BIN is in RAM */
void char_tables_init(void);

/* where the table that was at dc is now (dc when it wasn't moved) */
uint32_t char_table_moved(uint32_t dc);
